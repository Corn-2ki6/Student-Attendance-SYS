SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS attendance_records;
DROP TABLE IF EXISTS attendance_sessions;
DROP TABLE IF EXISTS schedules;
DROP TABLE IF EXISTS enrollments;
DROP TABLE IF EXISTS class_sections;
DROP TABLE IF EXISTS courses;
DROP TABLE IF EXISTS lecturers;
DROP TABLE IF EXISTS students;
DROP TABLE IF EXISTS users;

CREATE TABLE users (
    userID INT AUTO_INCREMENT PRIMARY KEY,
    userName VARCHAR(50) NOT NULL UNIQUE,
    passwordHash VARCHAR(255) NOT NULL,
    fullName VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    role VARCHAR(20) NOT NULL DEFAULT 'STUDENT'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE students (
    studentID INT AUTO_INCREMENT PRIMARY KEY,
    userID INT NOT NULL UNIQUE,
    studentCode VARCHAR(20) NOT NULL UNIQUE,
    fullName VARCHAR(100) NOT NULL,
    dateOfBirth DATE NULL,
    gender VARCHAR(20) NULL,
    major VARCHAR(100) NULL,
    CONSTRAINT fk_students_user FOREIGN KEY (userID) REFERENCES users(userID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE lecturers (
    lecturerID INT AUTO_INCREMENT PRIMARY KEY,
    userID INT NOT NULL UNIQUE,
    lecturerCode VARCHAR(20) NOT NULL UNIQUE,
    fullName VARCHAR(100) NOT NULL,
    department VARCHAR(100) NULL,
    CONSTRAINT fk_lecturers_user FOREIGN KEY (userID) REFERENCES users(userID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE courses (
    courseID INT AUTO_INCREMENT PRIMARY KEY,
    courseCode VARCHAR(20) NOT NULL UNIQUE,
    courseName VARCHAR(150) NOT NULL,
    credits INT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE class_sections (
    classID INT AUTO_INCREMENT PRIMARY KEY,
    courseID INT NOT NULL,
    lecturerID INT NOT NULL,
    classCode VARCHAR(30) NOT NULL UNIQUE,
    semester VARCHAR(20) NOT NULL,
    academicYear VARCHAR(20) NOT NULL,
    CONSTRAINT fk_classes_course FOREIGN KEY (courseID) REFERENCES courses(courseID),
    CONSTRAINT fk_classes_lecturer FOREIGN KEY (lecturerID) REFERENCES lecturers(lecturerID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE enrollments (
    enrollmentID INT AUTO_INCREMENT PRIMARY KEY,
    studentID INT NOT NULL,
    classID INT NOT NULL,
    enrollmentDate DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    CONSTRAINT fk_enrollments_student FOREIGN KEY (studentID) REFERENCES students(studentID),
    CONSTRAINT fk_enrollments_class FOREIGN KEY (classID) REFERENCES class_sections(classID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE schedules (
    scheduleID INT AUTO_INCREMENT PRIMARY KEY,
    classID INT NOT NULL,
    dayOfWeek VARCHAR(20) NOT NULL,
    startTime TIME NOT NULL,
    endTime TIME NOT NULL,
    room VARCHAR(50) NOT NULL,
    CONSTRAINT fk_schedules_class FOREIGN KEY (classID) REFERENCES class_sections(classID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE attendance_sessions (
    sessionID INT AUTO_INCREMENT PRIMARY KEY,
    classID INT NOT NULL,
    sessionDate DATE NOT NULL,
    startTime TIME NOT NULL,
    endTime TIME NOT NULL,
    attendanceMethod VARCHAR(20) NOT NULL,
    attendancePasswordHash VARCHAR(255) NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED',
    CONSTRAINT fk_sessions_class FOREIGN KEY (classID) REFERENCES class_sections(classID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE attendance_records (
    attendanceID INT AUTO_INCREMENT PRIMARY KEY,
    sessionID INT NOT NULL,
    studentID INT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    checkInTime DATETIME NULL,
    method VARCHAR(20) NULL,
    remark VARCHAR(255) NULL,
    CONSTRAINT fk_records_session FOREIGN KEY (sessionID) REFERENCES attendance_sessions(sessionID),
    CONSTRAINT fk_records_student FOREIGN KEY (studentID) REFERENCES students(studentID),
    CONSTRAINT uq_record_session_student UNIQUE (sessionID, studentID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

